"""
Calculadora de Soma

Desenvolva um programa que soma dois números.
Use as variáveis numero 1 = 12 e numero 2 = 14.
O programa deve calcular a soma e exibir o resultado.
"""

# Atribuição dos valores
numero1 = 12
numero2 = 14

# Cálculo da soma
soma = numero1 + numero2

# Exibição do resultado com f-string (atenção para o 'f' antes das aspas)
print(f"A soma numero1 = {numero1} e da variável numero2 = {numero2} é {soma}.")