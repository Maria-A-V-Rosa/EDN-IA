"""
Calculadora de Volume de uma Caixa Retangular

Este programa calcula o volume de uma caixa com as dimensões:
Comprimento = 12 cm
Largura = 14 cm
Altura = 20 cm

A fórmula do volume é:
Volume = Comprimento × Largura × Altura
"""

# Atribuição das dimensões da caixa
comprimento = 12  # em centímetros
largura = 14      # em centímetros
altura = 20       # em centímetros

# Cálculo do volume
volume = comprimento * largura * altura

# Exibição do resultado
print(f"O volume da caixa é {volume} cm³.")