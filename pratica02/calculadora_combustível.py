# Distância total percorrida na viagem
distancia = 300  # km

# Combustível total gasto durante a viagem
combustivel = 25  # litros

# Cálculo do consumo médio: km percorridos por litro de combustível
consumo_medio = distancia / combustivel

# Exibição dos dados da viagem e do resultado final formatado com duas casas decimais
print("Dados da viagem:")
print(f"Distância percorrida: {distancia} km")
print(f"Combustível gasto: {combustivel} litros")
print(f"Consumo médio: {consumo_medio:.2f} km/l")